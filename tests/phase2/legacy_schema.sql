CREATE SQL SECURITY INVOKER VIEW `view_annual_jmrc_payments` AS select `e`.`user_id` AS `user_id`,year(`ev`.`event_date`) AS `target_year`,max(case when `e`.`personal_member_choice` in ('登録済','今回入会') then 1 else 0 end) AS `is_member_paid`,max(case when `f`.`item_name` in ('JMRC共済掛金(免責無)','JMRC共済掛金(免責有)') then 1 else 0 end) AS `is_mutual_aid_paid` from (((`jmrc_entries` `e` join `entrants` `en` on(`e`.`user_id` = `en`.`user_id`)) join `jmrc_events` `ev` on(`e`.`event_id` = `ev`.`id`)) left join `jmrc_entry_fees` `f` on(`e`.`id` = `f`.`entry_id`)) where `e`.`status` = 'accepted' group by `e`.`user_id`,year(`ev`.`event_date`);
